"""
Experimental Benchmarks Router.
Connects the ML Engine's controlled drift benchmark suite (Detection Delay,
False Alarm Rate, t-digest Quantile Error, CBPE Accuracy) directly to the
FastAPI backend and Interactive Web Dashboard.
"""

from typing import Any, Dict
from fastapi import APIRouter, Depends, HTTPException

from backend.app.services.drift_service import DriftService

router = APIRouter(prefix="/api/v1/benchmarks", tags=["Benchmarks & Evaluation"])


def get_drift_service() -> DriftService:
    return DriftService.get_instance()


@router.get("/results", summary="Get Experimental Benchmark Results")
def get_benchmark_results(
    service: DriftService = Depends(get_drift_service),
) -> Dict[str, Any]:
    """
    Retrieves the quantitative evaluation benchmark tables generated by the
    ML Engine: Detection Delay across drift types, t-digest Quantile Accuracy,
    and full Markdown experimental summary.
    """
    try:
        return service.get_benchmark_results()
    except Exception as e:
        raise HTTPException(
            status_code=500, detail=f"Failed to load benchmark results: {str(e)}"
        )


@router.post("/run", summary="Run Full Benchmark Suite Live")
def run_benchmarks(
    service: DriftService = Depends(get_drift_service),
) -> Dict[str, Any]:
    """
    Executes the complete experimental benchmark suite (Abrupt, Gradual,
    Recurring, Feature-Specific drift, Sketch accuracy, CBPE error, and
    Multivariate sensitivity) and regenerates all reports.
    """
    try:
        return service.run_live_benchmarks()
    except Exception as e:
        raise HTTPException(
            status_code=500, detail=f"Failed to execute benchmarks: {str(e)}"
        )
